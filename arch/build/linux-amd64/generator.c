#include "build/build.h"
#include "build/generator.h"
#include "fundamental/string/string.h"

BuildGenerationResult build_generate_for_platform(SourceScanResult scan_result)
{
	static char script_buffer[16384];
	static char sources_buffer[MAX_SOURCES_LENGTH];
	char name[64];

	if (!build_ini_read_name(name, sizeof(name))) {
		fun_string_copy((String) "app", name, sizeof(name));
	}

	build_sources_string(scan_result, sources_buffer, sizeof(sources_buffer));

	char *ptr = script_buffer;
	char *buf_end = script_buffer + sizeof(script_buffer);

	ptr = build_append(
		ptr,
		"#!/bin/bash\n"
		"# Build script generated by fun build tool\n"
		"# Platform: linux-amd64\n"
		"\n"
		"mkdir -p build\n"
		"\n"
		"# Compile with GCC\n"
		"gcc --std=c17 -Os -nostdlib -fno-builtin -fno-exceptions"
		" -fno-unwind-tables"
		" -I . -I include -I src -I vendor/fundamental/include ",
		buf_end);

	ptr = build_append(ptr, sources_buffer, buf_end);

	ptr = build_append(ptr, " -o build/", buf_end);

	ptr = build_append(ptr, name, buf_end);
	ptr = build_append(ptr, "-linux-amd64\n\n", buf_end);
	ptr = build_append(ptr, "strip --strip-unneeded build/", buf_end);
	ptr = build_append(ptr, name, buf_end);
	ptr = build_append(ptr, "-linux-amd64\n\n", buf_end);
	ptr = build_append(ptr, "echo Build complete: build/", buf_end);
	ptr = build_append(ptr, name, buf_end);
	ptr = build_append(ptr, "-linux-amd64\n", buf_end);
	*ptr = '\0';

	return build_write_script("build-linux-amd64.sh", script_buffer);
}
